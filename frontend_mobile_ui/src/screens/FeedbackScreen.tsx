import { Feather } from "@expo/vector-icons";
import type { NativeStackScreenProps } from "@react-navigation/native-stack";
import React, { useEffect, useState } from "react";
import {
  ActivityIndicator,
  Pressable,
  ScrollView,
  StyleSheet,
  Text,
  View,
} from "react-native";

import { BloomIcon } from "@/components/BloomIcon";
import { PrimaryButton } from "@/components/PrimaryButton";
import { ScreenContainer } from "@/components/ScreenContainer";
import type { RootStackParamList } from "@/navigation/types";
import { fetchSessionFeedback } from "@/services/sessionService";
import { colors, fonts, radius, spacing } from "@/theme/tokens";
import type { SessionFeedback } from "@/types";

type Props = NativeStackScreenProps<RootStackParamList, "Feedback">;

export function FeedbackScreen({ route, navigation }: Props) {
  const { sessionId, scenarioLabel } = route.params;
  const [feedback, setFeedback] = useState<SessionFeedback | null>(null);

  useEffect(() => {
    let cancelled = false;
    fetchSessionFeedback(sessionId, scenarioLabel).then(
      (data) => !cancelled && setFeedback(data),
    );
    return () => {
      cancelled = true;
    };
  }, [sessionId, scenarioLabel]);

  if (!feedback) {
    return (
      <ScreenContainer>
        <View style={styles.loading}>
          <ActivityIndicator color={colors.purpleDeep} />
        </View>
      </ScreenContainer>
    );
  }

  return (
    <ScreenContainer>
      <ScrollView
        contentContainerStyle={styles.scroll}
        showsVerticalScrollIndicator={false}
      >
        <View style={styles.titleRow}>
          <View style={styles.titleIcon}>
            <BloomIcon size={15} />
          </View>
          <Text style={styles.titleLabel}>Session feedback</Text>
        </View>

        <View>
          <Text style={styles.eyebrow}>{feedback.scenarioLabel}</Text>
          <Text style={styles.headline}>{feedback.headline}</Text>
        </View>

        <View style={styles.scoreCard}>
          <View>
            <Text style={styles.scoreCaption}>
              {feedback.cleanSentenceCount} of {feedback.totalSentenceCount}{" "}
              sentences were clean
            </Text>
            <Text style={styles.scoreSubcaption}>
              That&apos;s a strong foundation.
            </Text>
          </View>
          <Text style={styles.scoreValue}>{feedback.overallScore}</Text>
        </View>

        <Text style={styles.sectionLabel}>Your garden notes</Text>
        <View style={{ gap: spacing.sm }}>
          {feedback.notes.map((note) => (
            <View key={note.id} style={styles.noteCard}>
              <View
                style={[
                  styles.noteDot,
                  {
                    backgroundColor:
                      note.kind === "praise" ? colors.sage : colors.rose,
                  },
                ]}
              >
                <Feather
                  name={note.kind === "praise" ? "check" : "minus"}
                  size={12}
                  color={colors.white}
                />
              </View>
              <View style={{ flex: 1 }}>
                <Text style={styles.noteText}>{note.original}</Text>
                {note.kind === "praise" ? (
                  <Text style={styles.notePraise}>{note.note}</Text>
                ) : (
                  <Text style={styles.noteHint}>
                    Try:{" "}
                    <Text style={styles.noteSuggestion}>
                      &quot;{note.suggestion}&quot;
                    </Text>
                  </Text>
                )}
              </View>
            </View>
          ))}
        </View>

        <View>
          <Text style={styles.sectionLabel}>Your strengths</Text>
          <View
            style={{
              flexDirection: "row",
              gap: spacing.sm,
              marginTop: spacing.sm,
            }}
          >
            {feedback.strengths.map((strength) => (
              <View key={strength} style={styles.strengthChip}>
                <Text style={styles.strengthLabel}>{strength}</Text>
              </View>
            ))}
          </View>
        </View>
      </ScrollView>

      <View style={styles.footer}>
        <PrimaryButton
          label="Fix your top pattern"
          icon={<Feather name="arrow-right" size={16} color={colors.white} />}
          onPress={() => navigation.navigate("Drill", { sessionId })}
        />
        <Pressable
          onPress={() =>
            navigation.navigate("Report", {
              sessionId,
              scenarioLabel,
              durationMinutes: 5,
            })
          }
        >
          <Text style={styles.reportLink}>View full report &rarr;</Text>
        </Pressable>
        <Text style={styles.footnote}>Feedback generated by AI</Text>
      </View>
    </ScreenContainer>
  );
}

